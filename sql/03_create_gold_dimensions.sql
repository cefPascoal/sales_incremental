CREATE SCHEMA IF NOT EXISTS gold;

CREATE TABLE IF NOT EXISTS gold.dim_loja (
  loja_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa VARCHAR(40) NOT NULL,
  loja_id VARCHAR(40) NOT NULL,
  loja_nome VARCHAR(120),
  cidade VARCHAR(120),
  CONSTRAINT uq_dim_loja_empresa_loja UNIQUE (empresa, loja_id)
);

CREATE TABLE IF NOT EXISTS gold.dim_produto (
  produto_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa VARCHAR(40) NOT NULL,
  sku VARCHAR(80) NOT NULL,
  produto VARCHAR(255),
  categoria VARCHAR(120),
  CONSTRAINT uq_dim_produto_empresa_sku UNIQUE (empresa, sku)
);

CREATE TABLE IF NOT EXISTS gold.dim_vendedor (
  vendedor_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  empresa VARCHAR(40) NOT NULL,
  vendedor VARCHAR(120) NOT NULL,
  CONSTRAINT uq_dim_vendedor_empresa_nome UNIQUE (empresa, vendedor)
);

CREATE TABLE IF NOT EXISTS gold.dim_metodo_pagamento (
  metodo_pagamento_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  metodo_pagamento VARCHAR(80) NOT NULL UNIQUE
);
