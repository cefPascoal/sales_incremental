CREATE SCHEMA IF NOT EXISTS gold;

CREATE TABLE IF NOT EXISTS gold.fact_vendas (
  fact_venda_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_record_key TEXT NOT NULL,
  data_key INTEGER NOT NULL,
  loja_key BIGINT,
  produto_key BIGINT,
  vendedor_key BIGINT,
  metodo_pagamento_key BIGINT,
  id_venda VARCHAR(80) NOT NULL,
  linha INTEGER NOT NULL,
  quantidade INTEGER NOT NULL,
  preco_unit NUMERIC(12, 2) NOT NULL,
  desconto_pct NUMERIC(5, 4),
  valor_desconto NUMERIC(12, 2),
  total_linha NUMERIC(12, 2) NOT NULL,
  timestamp_envio TIMESTAMP WITHOUT TIME ZONE,
  nome_ficheiro TEXT,
  data_ingestao TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_fact_vendas_calendario
    FOREIGN KEY (data_key) REFERENCES gold.dim_calendario (data_key),
  CONSTRAINT fk_fact_vendas_loja
    FOREIGN KEY (loja_key) REFERENCES gold.dim_loja (loja_key),
  CONSTRAINT fk_fact_vendas_produto
    FOREIGN KEY (produto_key) REFERENCES gold.dim_produto (produto_key),
  CONSTRAINT fk_fact_vendas_vendedor
    FOREIGN KEY (vendedor_key) REFERENCES gold.dim_vendedor (vendedor_key),
  CONSTRAINT fk_fact_vendas_metodo_pagamento
    FOREIGN KEY (metodo_pagamento_key)
    REFERENCES gold.dim_metodo_pagamento (metodo_pagamento_key),
  CONSTRAINT uq_fact_vendas_source_record UNIQUE (source_record_key)
);

ALTER TABLE gold.fact_vendas
  ADD COLUMN IF NOT EXISTS source_record_key TEXT;

UPDATE gold.fact_vendas
SET source_record_key = md5('existing-fact-' || fact_venda_key::text)
WHERE source_record_key IS NULL;

ALTER TABLE gold.fact_vendas
  ALTER COLUMN source_record_key SET NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_fact_vendas_source_record
  ON gold.fact_vendas (source_record_key);

CREATE INDEX IF NOT EXISTS ix_fact_vendas_data_key
  ON gold.fact_vendas (data_key);

CREATE INDEX IF NOT EXISTS ix_fact_vendas_loja_key
  ON gold.fact_vendas (loja_key);

CREATE INDEX IF NOT EXISTS ix_fact_vendas_produto_key
  ON gold.fact_vendas (produto_key);
